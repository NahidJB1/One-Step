'use strict';
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),ownership=require('../data/fee_page_ownership.json').universities;
const source=require('../data/legacy_redirect_routes.json');
const origin='https://www.onestepmy.com';
const aliases=source.map(r=>({...r}));
for(const r of aliases){
 for(const u of Object.values(ownership))if(u.owner==='fee')r.pattern=r.pattern.replace(`(?:Universities/${u.id}-details|Fees_Chart/${u.id}-fees)`,`Universities/${u.id}-details`);
 if(/^\^Fees_Chart\/city-university-fees/.test(r.pattern))r.target=ownership.cityu.ownerPath;
 if(/^\/Fees_Chart\/(.+)-fees$/.test(r.target)){
  const id=r.target.match(/^\/Fees_Chart\/(.+)-fees$/)[1];if(ownership[id])r.target=ownership[id].ownerPath;
 }
 r.pattern=r.pattern.replace(/\$$/,'/*$');
}
const file=path.join(root,'.htaccess'),before=fs.readFileSync(file,'utf8').replace(/\r\n/g,'\n');
let start=before.indexOf('# Canonical page redirects.');if(start<0)start=before.indexOf('# Normalize literal repeated slashes');
const end=before.indexOf('# Serve only existing extensionless pages');
if(start<0||end<start)throw Error('Unknown .htaccess boundaries');
const lines=[
'# Canonical page redirects. Generated by scripts/build_fee_ownership_routing.cjs.',
'# Deploy these rules before disabling the separate Hostinger HTTPS redirect.',
'RewriteCond %{REQUEST_METHOD} !^(?:GET|HEAD)$',
'RewriteRule ^ - [END]',
'RewriteRule ^(?:api|assets|db|scripts|tests|docs|node_modules|includes)(?:/|$) - [END,NC]',
'RewriteRule \\.php(?:/|$) - [END,NC]',
'# No redirects to noindex utilities, except the approved application exception.',
'RewriteRule ^(register|verify|dev|bot_tester|404)(?:\\.html)?/*$ $1.html [END]',
'',
'# Historical details stay with the guide; fee redirects follow the owner ledger.',
...aliases.flatMap(r=>['RewriteCond %{HTTP_HOST} ^(?:www\\.)?onestepmy\\.com$ [NC]',`RewriteRule ${r.pattern} ${origin+r.target} [R=301,L,QSD]`]),
'',
'RewriteCond %{HTTP_HOST} ^(?:www\\.)?onestepmy\\.com$ [NC]',
'RewriteCond %{THE_REQUEST} \\s/+index(?:\\.html)?/*[?\\s] [NC]',
`RewriteRule ^index(?:\\.html)?/*$ ${origin}/ [R=301,L]`,
'',
'# THE_REQUEST excludes the internal extensionless-to-.html rewrite.',
'RewriteCond %{HTTP_HOST} ^(?:www\\.)?onestepmy\\.com$ [NC]',
'RewriteCond %{THE_REQUEST} \\s/+[^?\\s]*\\.html/*[?\\s] [NC]',
'RewriteCond %{DOCUMENT_ROOT}/$1.html -f',
`RewriteRule ^(.+?)\\.html/*$ ${origin}/$1 [R=301,L,NE]`,
'',
'RewriteCond %{HTTP_HOST} ^(?:www\\.)?onestepmy\\.com$ [NC]',
'RewriteCond %{DOCUMENT_ROOT}/$1.html -f',
`RewriteRule ^(.+?)/+$ ${origin}/$1 [R=301,L,NE]`,
'',
'RewriteCond %{HTTP_HOST} ^(?:www\\.)?onestepmy\\.com$ [NC]',
'RewriteCond %{HTTPS} !=on [OR]',
'RewriteCond %{HTTP_HOST} !^www\\.onestepmy\\.com$ [NC]',
`RewriteRule ^ ${origin}%{REQUEST_URI} [R=301,L,NE]`,
'',
'ErrorDocument 404 /404.html',
''];
const after=before.slice(0,start)+lines.join('\n')+'\n'+before.slice(end);
const changed=after!==before;
if(changed&&!process.argv.includes('--check'))fs.writeFileSync(file,after);
if(changed&&process.argv.includes('--check'))process.exitCode=1;
console.log(`${changed?'Updated':'Current'} ownership routing; ${aliases.length} legacy rules. Static output only.`);
module.exports=aliases;
